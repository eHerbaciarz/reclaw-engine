#!/usr/bin/env python3
"""List of the port's own menu / screen texts for translators (stdlib only).

    python3 scripts/make_lang_strings.py

Collects every Lang::Tr("polski", "English") from the engine and writes

  Build_Release/lang/pl/menu/strings.txt   English = Polish (the current texts)
  Build_Release/lang/en/menu/strings.txt   English = English
  Build_Release/lang/xx/menu/strings.txt   English = (empty) - a new language

A copy put into <ReClaw folder>/lang/<code>/menu/strings.txt replaces the
built-in texts: change the right side only. A new language (e.g. "de"): copy
xx/ to lang/de/, fill it in and set <Language>de</Language> in config.xml.
Lines without a translation keep the English text. "quotes" keep spaces at
the ends, \\n is a new line, # starts a comment.
"""
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "OpenClaw", "Engine")
OUT = os.path.join(REPO, "Build_Release", "lang")

STR = r'"((?:[^"\\]|\\.)*)"'
TR = re.compile(r'Lang::Tr\(\s*' + STR + r'\s*,\s*' + STR + r'\s*\)')


def c_unescape(s):
    return s.replace('\\"', '"').replace("\\n", "\n").replace("\\\\", "\\")


def file_escape(s):
    s = s.replace("\n", "\\n")
    if s != s.strip() or " = " in s:
        s = '"' + s + '"'
    return s


def main():
    pairs = {}
    order = []
    for root, _dirs, files in os.walk(SRC):
        for name in sorted(files):
            if not name.endswith((".cpp", ".h")):
                continue
            path = os.path.join(root, name)
            rel = os.path.relpath(path, REPO)
            text = open(path, encoding="utf-8", errors="replace").read()
            for m in TR.finditer(text):
                pl, en = c_unescape(m.group(1)), c_unescape(m.group(2))
                if en not in pairs:
                    pairs[en] = (pl, rel)
                    order.append(en)

    header = ("# ReClaw - texts of the menus and screens added by the port\n"
              "# Format: English text = translation (change the right side only)\n"
              "# Generated by scripts/make_lang_strings.py\n")
    for code in ("pl", "en", "xx"):
        out_dir = os.path.join(OUT, code, "menu")
        os.makedirs(out_dir, exist_ok=True)
        with open(os.path.join(out_dir, "strings.txt"), "w", encoding="utf-8", newline="\n") as f:
            f.write(header)
            last_file = None
            for en in order:
                pl, rel = pairs[en]
                if rel != last_file:
                    f.write("\n# " + rel.replace(os.sep, "/") + "\n")
                    last_file = rel
                value = {"pl": pl, "en": en, "xx": ""}[code]
                line = file_escape(en) + " = " + (file_escape(value) if value else "")
                f.write(line.rstrip() + "\n")
    print("%d texts -> %s" % (len(order), os.path.relpath(OUT, REPO)))


if __name__ == "__main__":
    main()
